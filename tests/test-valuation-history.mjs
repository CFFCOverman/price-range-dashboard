import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { estimateRowsVerdict } from '../fetcher/steps/estimates.mjs';
import { valuationDates, scalarFql, valuationVerdict } from '../fetcher/lib/valuation-history.mjs';
const c=vm.createContext({console,Map,Date});
for(const f of ['core/state','core/utils','core/i18n','ingest/companies','ingest/estimates','valuation/calc'])
  vm.runInContext(fs.readFileSync(`src/js/${f}.js`,'utf8'),c);
const run=s=>vm.runInContext(s,c);
c.ntm=Array.from({length:12},(_,i)=>({ticker:' TST-US ',date:`2025-${String(i+1).padStart(2,'0')}-28`,pe_ntm:String(10+i),eps_ntm:'5',valuation_basis:'ntm'}));
c.fixed=[['TST-US'],['Estimate History',"Dec '26E"],['Date','Mean','Low','High','P/E (x)'],
  ...Array.from({length:24},(_,i)=>{const d=new Date(Date.UTC(2026,8-i,28));return [`28 ${['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][d.getUTCMonth()]} '${String(d.getUTCFullYear()).slice(-2)}`,3,2,4,30+i];})];
run("ingestEstimateSheet('TST-US',fixed,'TST-US FY1 Estimate History.xlsx'); ingestHistory(ntm)");
assert.equal(run("state.history.get('TST-US').length"),12);
assert.equal(run("peStats('TST-US').p50"),15.5);
run("ingestEstimateSheet('TST-US',fixed,'TST-US FY1 Estimate History.xlsx')");
assert.equal(run("peStats('TST-US').basis"),'ntm');
assert.equal(run("peStats('TST-US').p50"),15.5,'shorter NTM wins over longer fixed-year in both load orders');
run("ingestHistory([...ntm, {...ntm.at(-1),pe_ntm:'24'}])");
assert.equal(run("state.history.get('TST-US').length"),12,'duplicate dates cannot inflate sample count');
assert.equal(run("peStats('TST-US').current"),24);
run("ingestHistory([{ticker:'TST-US',date:'2026-09-29',pe_ntm:'99'}])");
assert.equal(run("peStats('TST-US').current"),24,'partial import preserves valid series');
assert.equal(run("baseGap(120,peStats('TST-US'),{mean:1})"),null,'NTM identity uses NTM EPS, not FY1');
assert.equal(run("baseGap(120,{...peStats('TST-US'),currentEps:NaN},{mean:1})"),null);
assert.equal(run("calcRange(state.companies.get('TST-US'),'fy1').mid"),46.5,'FY scenario remains explicit');
const missingPE=Array.from({length:24},()=>["28 Sep '26",'3.60','-','42','2','4','3.51','4.00','0.08','0','0','-','-']);
assert.equal(estimateRowsVerdict('FY1',missingPE).ok,false,'legacy strict P/E check retained');
assert.equal(estimateRowsVerdict('FY1',missingPE,{requirePe:false}).ok,true,'independent EPS capture succeeds without P/E');
assert.equal(estimateRowsVerdict('FY1',[["28 Sep '26",'-']],{requirePe:false}).ok,false,'missing earnings still rejected');
console.log('PASS valuation history: source priority, import order, duplicate dates, partial refresh, NTM identity, independent EPS');
const dates=valuationDates('2026-09-29');
assert.equal(dates.length,121);
assert.equal(dates[0],'2016-09-30');
assert.equal(dates.at(-2),'2026-08-31');
assert.equal(dates.at(-1),'2026-09-29');
assert.ok(valuationDates('2024-03-01',1).includes('2024-02-29'));
assert.throws(()=>valuationDates('2026-02-31'));
const reply=[{$symbol:'NFLX-USA',$expression:'P_PRICE(20260928)',$error:0,$value:[[69.23]]}];
assert.equal(scalarFql(reply,'NFLX-US','P_PRICE(20260928)'),69.23);
assert.throws(()=>scalarFql(reply,'META-US','P_PRICE(20260928)'));
assert.throws(()=>scalarFql(reply,'NFLX-US','P_PRICE(20250828)'));
assert.equal(scalarFql([{...reply[0],$value:[['NA']]}],'NFLX-US','P_PRICE(20260928)'),null);
assert.throws(()=>scalarFql([{...reply[0],$error:1}],'NFLX-US','P_PRICE(20260928)'));
const history=dates.map(date=>({date,price:100,eps_ntm:5,pe_ntm:20}));
assert.equal(valuationVerdict(history).ok,true);
assert.equal(valuationVerdict(history.map(r=>({...r,eps_ntm:null}))).ok,false);
assert.equal(valuationVerdict([...history.slice(0,-1),{...history.at(-1),price:null}]).ok,false);
assert.equal(valuationVerdict([...history.slice(0,-1),{...history.at(-1),eps_ntm:2}]).ok,false);
console.log('PASS valuation fetch: first-run 10y schedule, leap month, symbol/date identity, API errors, coverage, earnings/price basis');
