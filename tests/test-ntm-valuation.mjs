import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import os from 'node:os';
import { metaEst, metaValuation } from '../fetcher/lib/registry.mjs';
import { freshHoursFor } from '../fetcher/lib/companies.mjs';

const c=vm.createContext({console,Map,Date});
for(const f of ['core/state','core/utils','core/i18n','ingest/companies','ingest/estimates','valuation/calc'])
  vm.runInContext(fs.readFileSync(`src/js/${f}.js`,'utf8'),c);
const run=s=>vm.runInContext(s,c);
const near=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} != ${expected}`);
assert.equal(run('state.horizon'),'ntm');
const rows=Array.from({length:121},(_,i)=>{
  const d=new Date(Date.UTC(2016,8+i,28));
  return {ticker:'TST',date:d.toISOString().slice(0,10),pe_ntm:i<60?'40':i<96?'30':'20',eps_ntm:'10',price:i<60?'400':i<96?'300':'200',valuation_basis:'ntm'};
});
c.rows=rows;
run("ingestCompanies([{ticker:'TST',price:'200',price_date:'2026-09-28',eps_fy1_mean:'5',eps_fy1_low:'4',eps_fy1_high:'6'}]);ingestHistory(rows)");
near(run("calcRange(state.companies.get('TST'),'ntm').mid"),300);
near(run("calcRange(state.companies.get('TST'),'fy1').mid"),150);
assert.equal(run("peStats('TST',3).series.length"),37);
assert.equal(run("peStats('TST',5).series.length"),61);
assert.equal(run("peStats('TST',10).series.length"),121);
near(run("calcRange(state.companies.get('TST'),'ntm',3).mid"),200);
run("state.companies.get('TST').price=160");
near(run("latestValuation(state.companies.get('TST')).current"),16);
near(run("latestValuation(state.companies.get('TST')).change"),-.2);
run("ingestHistory([{ticker:'TST',date:'2026-09-29',price:'160',eps_ntm:'8',pe_ntm:'20'}])");
near(run("latestValuation(state.companies.get('TST')).current"),20);
near(run("latestValuation(state.companies.get('TST')).earningsEffect"),.25);
near(run("calcRange(state.companies.get('TST'),'ntm').mid"),240);
assert.equal(run("state.history.get('TST').length"),121,'partial current refresh preserves historical library');
run("state.overrides.set('TST|ntm',{low:6,mean:7,high:9})");
near(run("calcRange(state.companies.get('TST'),'ntm').mid"),210);
near(run("latestValuation(state.companies.get('TST')).current"),20,'manual scenario does not alter observed PE');
run("state.overrides.clear(); ingestHistory([{ticker:'TST',date:'2026-09-30',eps_ntm:'-1',pe_ntm:''}]); ingestHistory(rows)");
assert.equal(run("calcRange(state.companies.get('TST'),'ntm')"),null,'no stale positive EPS or FY substitution');
assert.equal(run("latestValuation(state.companies.get('TST')).current"),null);
run("ingestHistory([{ticker:'TST',date:'2026-10-01',pe_ntm:'20',eps_ntm:''}])");
assert.equal(run("calcRange(state.companies.get('TST'),'ntm')"),null);
run("state.history.set('FIX',Array.from({length:24},(_,i)=>({date:'2026-'+String(i+1).padStart(2,'0')+'-01',pe:20,basis:'fixed_fy1'})));state.ntmEstimates.set('FIX',{date:'2026-09-30',mean:5});state.companies.set('FIX',{ticker:'FIX',price:100,eps:{fy1:{mean:5}}})");
assert.equal(run("calcRange(state.companies.get('FIX'),'ntm')"),null,'fixed FY history cannot masquerade as NTM');
c.sheet=[['TST'],['Estimate History',"Dec '26E"],['Date','Mean','Low','High','P/E (x)'],["30 Sep '26",8,7,9,20],["31 Aug '26",10,9,11,20]];
run("ingestEstimateSheet('TST',sheet,'FY1.xlsx')");
near(run("state.companies.get('TST').estimateMeta.fy1.recentRevision"),-.2);
c.oldSheet=[...c.sheet.slice(0,3),["31 Aug '26",10,9,11,20]];
run("ingestEstimateSheet('TST',oldSheet,'FY1 Retry.xlsx')");
assert.equal(run("state.companies.get('TST').eps.fy1.mean"),8);
for(const m of [metaEst('TST','FY1'),metaValuation('TST'),{kind:'estimates'},{kind:'valuation'}]) assert.equal(freshHoursFor(m),0);
console.log('PASS NTM calculations: matched basis, windows, price reaction, earnings cuts, missing/loss, overrides, source protection and freshness');

const browser=await chromium.launch(process.env.PLAYWRIGHT_EXECUTABLE_PATH?{executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH}:{});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('price-range-dashboard.html')).href);
  await page.evaluate(rows=>{
    ingestCompanies([{ticker:'TST',name:'Test',currency:'USD',price:'200',price_date:'2026-09-28',eps_fy1_mean:'5',eps_fy1_low:'4',eps_fy1_high:'6'}]);
    ingestHistory(rows);state.selected='TST';renderAll();
  },rows);
  assert.equal(await page.locator('#valuationBasis').inputValue(),'ntm');
  assert.match(await page.locator('#latestValuation').innerText(),/20\.0x/);
  assert.equal(await page.locator('#valuationWindows tr').count(),4);
  await page.locator('#pxInput').fill('160');
  assert.match(await page.locator('#latestValuation').innerText(),/16\.0x/);
  await page.locator('#latestValuation').screenshot({path:path.join(os.tmpdir(),'prd-latest-pe-preview.png')});
  await page.locator('#valuationWindows').screenshot({path:path.join(os.tmpdir(),'prd-valuation-windows-preview.png')});
  await page.locator('#peWindow').selectOption('3');
  near(await page.evaluate(()=>calcRange(state.companies.get('TST'),state.horizon).mid),200);
  await page.locator('#valuationBasis').selectOption('fy1');
  assert.equal(await page.locator('#hzTabs .on').innerText(),'FY1');
  near(await page.evaluate(()=>calcRange(state.companies.get('TST'),state.horizon).mid),100);
  await page.locator('#hzTabs [data-h=ntm]').click();
  assert.equal(await page.locator('#valuationBasis').inputValue(),'ntm');
  await page.locator('#epsMean').fill('7');
  assert.match(await page.locator('#valuationWindows').innerText(),/手工/);
  assert.match(await page.locator('#latestValuation').innerText(),/16\.0x/);
  await page.locator('#epsReset').click();
  near(await page.evaluate(()=>epsFor('TST','ntm').mean),10);
  await page.locator('#langBtn').click();
  assert.match(await page.locator('#latestValuation').innerText(),/Current NTM P\/E/);
  assert.match(await page.locator('#ovTableWrap').innerText(),/Current NTM P\/E/);
  assert.deepEqual(errors,[]);
  console.log('PASS NTM browser: quote refresh, window/basis switching, scenario isolation, reset and translation');
} finally {await browser.close();}
