import assert from 'node:assert/strict';
import { buildOptionSignal } from '../fetcher/lib/option-flow-signal.mjs';
const before={timestamp:'2026-09-09T14:00:00Z',asof:'2026-09-09',spot:100,expiry:'2026-09-11',strike:100,call_volume:100,put_volume:100,call_bid:1,call_ask:1.2,call_last:1.2,call_delta:.5,put_bid:1,put_ask:1.2,put_last:1.2,put_delta:-.5};
const signal=(patch={},prior={})=>buildOptionSignal('TEST-US',[{...before,...prior}],[{...before,timestamp:'2026-09-09T14:15:00Z',call_volume:110,...patch}]);
assert.equal(signal().net_delta_shares,500);
assert.equal(signal({call_last:1}).direction,'bearish');
assert.equal(signal({call_volume:100,put_volume:110}).direction,'bearish');
assert.equal(signal({call_volume:100,put_volume:110,put_last:1}).direction,'bullish');
assert.equal(signal({call_bid:.01,call_ask:.02,call_last:.02}).direction,'unavailable');
assert.equal(signal({call_delta:.00001}).quality,'insufficient-exposure');
assert.equal(signal({put_volume:99}).quality,'volume-reset');
assert.equal(signal({call_volume:100}).quality,'no-new-volume');
assert.equal(signal({call_delta:''}).quality,'missing-delta');
assert.equal(signal({spot:101}).condition_state,'confirmed');
assert.equal(signal({spot:99}).condition_state,'invalidated');
assert.equal(signal({asof:'2026-09-10'}),null);
assert.equal(signal({source:'different'}),null);
assert.equal(signal({timestamp:'2026-09-09T17:00:00Z'}),null);
const missing={...before,strike:101,call_volume:1000,call_delta:''};
const coverage=buildOptionSignal('TEST-US',[before,missing],[{...before,timestamp:'2026-09-09T14:15:00Z',call_volume:110},{...missing,timestamp:'2026-09-09T14:15:00Z',call_volume:2000}]);
assert.equal(coverage.quality,'low-coverage');
console.log('Option flow regression tests passed (15 cases).');
assert.equal(signal({call_delta:2}).quality,'missing-delta');
assert.equal(signal({call_delta:-.5}).quality,'missing-delta');
assert.equal(signal().usable_contracts,10);
assert.equal(signal().match_coverage,1);
assert.equal(signal().expiry_count,1);
assert.equal(signal({ticker:'OTHER'}),null);
const extra={...before,strike:105,timestamp:'2026-09-09T14:15:00Z'};
assert.equal(buildOptionSignal('TEST-US',[before],[{...extra,strike:100,call_volume:110},extra]).quality,'low-match-coverage');
assert.equal(buildOptionSignal('TEST-US',[before,before],[extra]),null);
console.log('PASS audit metadata, invalid delta, batch identity, duplicate contracts, scope loss');
